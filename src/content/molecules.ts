// Banque de molécules vérifiées.
//
// Chaque entrée associe une structure (SMILES) au nom attendu ÉCRIT À LA MAIN.
// Les tests automatiques (molecules.test.ts) vérifient pour chaque molécule que :
//  - le SMILES est valide (valences respectées) ;
//  - le moteur de nomenclature produit exactement ce nom ;
//  - le nom, relu par l'analyseur de noms, redonne bien la même molécule.
// Pour étendre la banque : ajouter une ligne, puis lancer `npm test`.
//
// Niveaux : 1 débutant, 2 facile, 3 intermédiaire, 4 difficile, 5 niveau examen.

export interface MoleculeEntry {
  smiles: string;
  name: string;
  level: 1 | 2 | 3 | 4 | 5;
  skills: string[];
  /** Remarque pédagogique (convention, piège…). */
  note?: string;
}

